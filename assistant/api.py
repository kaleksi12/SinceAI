"""HTTP API for the web demo (FastAPI).

The React frontend (frontend/) talks only to these endpoints; all decisions are made by the dialogue engine
(dialogue.py), which keeps one conversation per session in memory.

  GET  /api/health      is the server up, and which model is configured
  GET  /api/scenarios   the demo starting points: five sample journeys (they carry sensitive signals, so the consent
                        flow can be shown) plus free text
  POST /api/chat        one chat turn. Reply type is "question", "consent_request" or "answer"
  POST /api/escalate    hand the case to a (simulated) human agent with a summary

Run:  uvicorn assistant.api:app --port 8000
"""
import os
import secrets
import threading
import time
from typing import Literal

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

from . import dialogue, kit

app = FastAPI(title="Digital Security Assistant (prototype)")

# Shown with every answer: the kit's guidance is synthetic and not DNA's advice.
DISCLAIMER = "Prototype. Advice is generated by AI from synthetic guidance and is not official DNA advice."
MAX_SESSIONS = 200  # oldest sessions are dropped beyond this (in-memory demo)

JOURNEY_LABELS = {
    "suspicious_message": "Suspicious message",
    "clicked_link": "I opened a link or installed something",
    "suspicious_call": "Suspicious call",
    "breach_notice": "Breach notice or account takeover signs",
    "smb_incident": "Small-business incident",
}
# One English dev case per journey, so the demo's starter messages are in English.
SAMPLE_CASE_IDS = {
    "suspicious_message": "DSA-D-0324",
    "clicked_link": "DSA-D-0079",
    "suspicious_call": "DSA-D-0003",
    "breach_notice": "DSA-D-0093",
    "smb_incident": "DSA-D-0283",
}
TARGET_LABELS = {
    "operator_support_agent": {"en": "an operator support agent", "fi": "operaattorin asiakaspalvelija", "sv": "en operatörssupportagent"},
    "security_specialist": {"en": "a security specialist", "fi": "tietoturva-asiantuntija", "sv": "en säkerhetsspecialist"},
    "human_advisor": {"en": "a human advisor", "fi": "ihmisneuvoja", "sv": "en mänsklig rådgivare"},
    "business_security_support": {"en": "business security support", "fi": "yritysten tietoturvatuki", "sv": "säkerhetssupport för företag"},
}
ESCALATION_TEXT = {
    "en": "Your case has been handed to %s with the summary shown below, so you do not need to explain it again. (Prototype: no real person is contacted.)",
    "fi": "Asiasi on välitetty: %s saa alla näkyvän yhteenvedon, joten sinun ei tarvitse kertoa sitä uudelleen. (Prototyyppi: oikeaa henkilöä ei kontaktoida.)",
    "sv": "Ditt ärende har skickats vidare till %s med sammanfattningen nedan, så du behöver inte förklara igen. (Prototyp: ingen verklig person kontaktas.)",
}

_sessions = {}  # session_id -> {"full_case", "state", "lock", "used"}
_sessions_lock = threading.Lock()


# --- request/response shapes ---------------------------------------------------------------------------------------

class ConsentReply(BaseModel):
    granted: list[str] = []
    refused: list[str] = []


class ChatRequest(BaseModel):
    session_id: str | None = None  # omitted on the first message of a conversation
    message: str | None = Field(None, max_length=4000)  # the user's text (opening message, or the answer to a question)
    consent: ConsentReply | None = None  # the user's answer to a consent_request
    scenario_id: str | None = None  # first message only: start from a sample journey
    audience: Literal["consumer", "small_business"] = "consumer"  # first message only, free text
    debug: bool = False  # also return the engine's internals for this turn (frontend debug view)


class EscalateRequest(BaseModel):
    session_id: str


# --- helpers --------------------------------------------------------------------------------------------------------

def _scenarios():
    """The sample journeys by id (the journey name). They are English dev cases, from the same scenario families as the
    kit's five Finnish samples; we never send their ground truth anywhere."""
    by_id = {c["case_id"]: c for c in kit.dev_cases()}
    return {journey: by_id[case_id] for journey, case_id in SAMPLE_CASE_IDS.items()}


def _free_case(audience):
    """A case for free text: an identified user, no pre-collected signals and nothing to ask consent for."""
    return {"case_id": "DEMO-" + secrets.token_hex(4), "split": "demo", "version": "demo", "journey": "free_text", "audience": audience,
            "locale": None, "language": None, "persona": {}, "entry_point": "operator_app_chat", "user_identified": True,
            "opening_message": "", "signals": {k: None for k in ("artifact", "link_check", "call_warning", "subscription", "device",
                                                                  "operator_account", "credential_exposure")},
            "signal_availability": {}, "consent": {"requires_consent": [], "pre_granted": []}}


def _get_session(session_id):
    with _sessions_lock:
        s = _sessions.get(session_id)
    if not s:
        raise HTTPException(404, "Unknown or expired session. Start a new conversation.")
    s["used"] = time.time()
    return s


def _new_session(full_case):
    sid = secrets.token_urlsafe(12)
    with _sessions_lock:
        if len(_sessions) >= MAX_SESSIONS:  # drop the least recently used
            del _sessions[min(_sessions, key=lambda k: _sessions[k]["used"])]
        _sessions[sid] = {"full_case": full_case, "state": {}, "lock": threading.Lock(), "used": time.time()}
    return sid, _sessions[sid]


def _citations(ids, lang):
    corpus = {g["id"]: g for g in kit.guidance()}
    return [{"id": i, "title": corpus[i].get("title_" + lang) or corpus[i]["title_en"]} for i in ids if i in corpus]


def _to_response(sid, state, reply):
    """Convert the engine's reply into what the frontend renders."""
    lang = state["lang"] or "en"
    if reply["type"] in ("question", "message"):  # "message": a follow-up reply after the advice (shown as plain text)
        return {"session_id": sid, "type": "question", "text": reply["text"]}
    if reply["type"] == "consent_request":
        fields = [{"path": p, "label": dialogue.field_label(p, lang)} for p in reply["fields"]]
        return {"session_id": sid, "type": "consent_request", "text": reply["text"], "consent_request": {"fields": fields}}
    a = reply["answer"]
    card = {"risk_level": a["risk_level"], "urgency": a["urgency"], "primary_action": a["primary_action"], "steps": a["steps"],
            "escalation_required": a["escalation_required"], "escalation_target": a["escalation_target"],
            "citations": _citations(a["citations"], lang), "signals_used": a["signals_used"], "confidence": a["confidence"],
            "abstained": a["abstained"], "disclaimer": DISCLAIMER}
    return {"session_id": sid, "type": "answer", "text": a["advice_text"], "answer": card}


# --- endpoints -------------------------------------------------------------------------------------------------------

@app.get("/api/health")
def health():
    return {"ok": True, "model": os.environ.get("LLM_MODEL") or None}


@app.get("/api/scenarios")
def scenarios():
    out = [{"id": "free_consumer", "label": "Free text: consumer", "audience": "consumer", "language": None, "opening_message": ""},
           {"id": "free_business", "label": "Free text: small business", "audience": "small_business", "language": None, "opening_message": ""}]
    for journey, c in _scenarios().items():
        out.append({"id": journey, "label": "Sample: " + JOURNEY_LABELS.get(journey, journey), "audience": c["audience"],
                    "language": c["language"], "opening_message": c["opening_message"]})
    return out


@app.post("/api/chat")
def chat(req: ChatRequest):
    if req.session_id is None:
        # First message: build the case (a sample journey or free text) and start the conversation.
        if not req.message or not req.message.strip():
            raise HTTPException(400, "Write a message to start.")
        if req.scenario_id and req.scenario_id in _scenarios():
            full = dict(_scenarios()[req.scenario_id])
        else:
            full = _free_case(req.audience)
        full["opening_message"] = req.message.strip()
        sid, s = _new_session(full)
        # visible_case() is the kit's own view of a case: no labels, and sensitive signals hidden until allowed.
        event = {"type": "start", "case": kit.visible_case(full)}
    else:
        sid, s = req.session_id, _get_session(req.session_id)
        full = s["full_case"]
        if req.consent is not None:
            allowed = set(full["consent"]["requires_consent"])
            granted = [p for p in req.consent.granted if p in allowed]
            refused = [p for p in req.consent.refused if p in allowed]
            event = {"type": "consent_reply", "granted": granted, "refused": refused,
                     "signals": kit.reveal_signals(full, granted),  # the real values, released only now
                     "text": "I allow that." if granted else "I would rather not share that."}
        elif req.message and req.message.strip():
            event = {"type": "user_reply", "text": req.message.strip()}
        else:
            raise HTTPException(400, "Send a message or a consent answer.")
    with s["lock"]:  # one turn at a time per conversation
        try:
            reply = dialogue.step(event, s["state"])
        except Exception as e:  # LLM/API trouble: do not leak details to the browser
            print("chat error:", type(e).__name__, str(e)[:200])
            raise HTTPException(502, "The assistant is temporarily unavailable. Please try again.")
        res = _to_response(sid, s["state"], reply)
        if req.debug:
            res["debug"] = s["state"].get("debug")
        return res


@app.post("/api/escalate")
def escalate(req: EscalateRequest):
    """Simulated handoff: returns the confirmation text and the summary that would be shared with a human agent."""
    s = _get_session(req.session_id)
    state = s["state"]
    summary = dialogue.handoff_summary(state)
    if summary is None:
        raise HTTPException(409, "There is nothing to escalate yet.")
    lang = state["lang"] or "en"
    target = summary["escalation_target"] or "human_advisor"
    text = ESCALATION_TEXT[lang] % TARGET_LABELS[target].get(lang, TARGET_LABELS[target]["en"])
    return {"text": text, "target": target, "summary": summary, "prototype": True}
